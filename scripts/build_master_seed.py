#!/usr/bin/env python3
"""Build the master-data seed migration from the pilot workbook.

Usage:  python3 scripts/build_master_seed.py "Fire Safety — Talabat Mart Pilot.xlsx" > supabase/migrations/20261120000003_master_data.sql

Migrates ONLY master data (decision 2026-11-20): zones, staff (no credentials), stores,
store base quantities, equipment types and default settings.
The PIN column is never read. Inspections / issues / audit history stay in the original
workbook as an archive and are not imported.
The script is read-only on the workbook and idempotent on the database (ON CONFLICT DO NOTHING).
"""
import sys, json
from openpyxl import load_workbook

def q(v):
    if v is None:
        return "null"
    return "'" + str(v).replace("'", "''") + "'"

def rows(ws):
    it = ws.iter_rows(values_only=True)
    hdr = [str(h).strip() if h is not None else "" for h in next(it)]
    for r in it:
        if any(c not in (None, "") for c in r):
            yield {h: v for h, v in zip(hdr, r)}

def main(path):
    wb = load_workbook(path, read_only=True, data_only=True)
    users = [r for r in rows(wb["Users"])]
    stores = [r for r in rows(wb["Stores"])]
    equip = [r for r in rows(wb["Store_Equipment"])]
    report = {"zones": 0, "staff": 0, "stores": 0, "store_equipment": 0, "warnings": []}

    out = ["-- Generated by scripts/build_master_seed.py — master data only, no credentials.",
           "begin;"]

    zones = sorted({str(s["zone"]).strip() for s in stores if s.get("zone")}, key=lambda z: (len(z), z))
    for i, z in enumerate(zones, 1):
        num = z.split()[-1]
        out.append(f"insert into public.zones(code,name_ar,name_en,sort) values ({q(z)},{q('المنطقة ' + num)},{q(z)},{i}) on conflict (code) do nothing;")
    report["zones"] = len(zones)

    for u in users:
        code = str(u["user_id"]).strip()
        name = str(u["name"]).strip()
        name = name[:1].upper() + name[1:]
        role = "admin" if str(u["role"]).strip().lower() == "admin" else "technician"
        zone = str(u.get("zone") or "").strip()
        zone_sql = f"(select id from public.zones where code={q(zone)})" if zone in zones else "null"
        active = "true" if str(u.get("active")).upper() in ("TRUE", "1") else "false"
        out.append(f"insert into public.staff(legacy_code,full_name,username,role,zone_id,active) values "
                   f"({q(code)},{q(name)},{q(code.lower())},{q(role)},{zone_sql},{active}) on conflict (legacy_code) do nothing;")
    report["staff"] = len(users)

    user_ids = {str(u["user_id"]).strip() for u in users}
    for s in stores:
        code = str(s["store_code"]).strip()
        tech = str(s.get("assigned_tech_id") or "").strip()
        if tech and tech not in user_ids:
            report["warnings"].append(f"store {code}: technician {tech} not in Users")
        tech_sql = f"(select id from public.staff where legacy_code={q(tech)})" if tech else "null"
        out.append("insert into public.stores(store_code,name,zone_id,assigned_tech_id,active,flagged) values "
                   f"({q(code)},{q(str(s['store_name']).strip())},(select id from public.zones where code={q(str(s['zone']).strip())}),"
                   f"{tech_sql},{'true' if s.get('active') in (True,'TRUE','true') else 'false'},{'true' if s.get('flag') in (True,'TRUE','true') else 'false'})"
                   " on conflict (store_code) do nothing;")
    report["stores"] = len(stores)

    codes = {str(s["store_code"]).strip() for s in stores}
    for e in equip:
        code = str(e["store_code"]).strip()
        if code not in codes:
            report["warnings"].append(f"equipment row for unknown store {code} skipped")
            continue
        vals = [int(e.get(k) or 0) for k in ("p6qty", "co2qty", "fsqty", "hcTotal")]
        out.append(f"insert into public.store_equipment(store_code,p6_qty,co2_qty,fs_qty,hc_total,updated_at) values "
                   f"({q(code)},{vals[0]},{vals[1]},{vals[2]},{vals[3]},{q(e.get('updated_at') or None)}::timestamptz) on conflict (store_code) do nothing;")
        report["store_equipment"] += 1
    missing = sorted(codes - {str(e['store_code']).strip() for e in equip})
    if missing:
        report["warnings"].append(f"{len(missing)} stores have no base quantities: {', '.join(missing)}")

    out += [
        "insert into public.equipment_types(code,name_ar,name_en,has_quantity,sort) values",
        "  ('p6','طفايات بودرة 6 كجم','6 kg powder extinguishers',true,1),",
        "  ('co2','طفايات CO2','CO2 extinguishers',true,2),",
        "  ('fs','معدات Fire Search','Fire Search equipment',true,3),",
        "  ('hc','خزائن خراطيم الحريق','Hose cabinets',true,4),",
        "  ('al','نظام إنذار الحريق','Fire alarm system',false,5),",
        "  ('fp','طرمبة الحريق','Fire pump',false,6)",
        "on conflict (code) do nothing;",
        "insert into public.app_settings(key,value) values",
        "  ('app_name_ar','\"إدارة السلامة من الحريق\"'),('app_name_en','\"Fire Safety Management\"'),",
        "  ('login_message_ar','\"سجّل دخولك باسم المستخدم وكلمة المرور\"'),('login_message_en','\"Sign in with your username and password\"'),",
        "  ('overdue_days','7'),('require_remarks_on_issue','false'),('session_idle_minutes','480'),('week_deadline_dow','6')",
        "on conflict (key) do nothing;",
        "commit;",
        "",
        "-- Expected counts after this migration:",
        f"--   zones={report['zones']} staff={report['staff']} stores={report['stores']} store_equipment={report['store_equipment']} equipment_types=6",
    ]
    for w in report["warnings"]:
        out.append(f"-- WARNING: {w}")
    print("\n".join(out))
    print(json.dumps(report, ensure_ascii=False), file=sys.stderr)

if __name__ == "__main__":
    main(sys.argv[1])
